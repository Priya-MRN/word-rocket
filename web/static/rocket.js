/* ============================================================================
   WORD ROCKET - front-end controller
   ----------------------------------------------------------------------------
   Talks to the Flask JSON API and drives the galaxy UI.

   ICON RULE: every icon is a lucide glyph, referenced via <svg><use> against
   the sprite generated by tools/icontool.py (web/templates/_icons.html) and
   included on the page. Icon *names* come from the server via window.WR_ICONS
   (built by hangman.icons). This file never writes SVG path geometry - only
   the sprite reference markup below.

   The 11 options live in localStorage under WR_SETTINGS and are applied by
   toggling data-* attributes on <html>, so CSS does the visual work.
   ========================================================================= */

(function () {
  "use strict";

  const code = document.body.dataset.code;
  const ICONS = window.WR_ICONS || {};
  const MAX_WRONG = 6;
  const KEYS_PER_PAGE = 12;
  const SVG_NS = "http://www.w3.org/2000/svg";

  // Build a sprite reference, e.g. iconEl("heart", "icon life-icon").
  function iconEl(name, className) {
    const svg = document.createElementNS(SVG_NS, "svg");
    if (className) svg.setAttribute("class", className);
    svg.setAttribute("aria-hidden", "true");
    const use = document.createElementNS(SVG_NS, "use");
    use.setAttribute("href", "#i-" + name);
    svg.appendChild(use);
    return svg;
  }

  /* --- Settings ----------------------------------------------------------- */

  const DEFAULTS = {
    category: "all",
    length: "any",
    text: "md",
    bigkeys: "off",
    paged: "off",
    motion: "on",
    sound: "on",
    speak: "off",
    hints: "on",
    two: "off",
    ui: "en",
  };

  function loadSettings() {
    try {
      return Object.assign({}, DEFAULTS, JSON.parse(localStorage.getItem("WR_SETTINGS") || "{}"));
    } catch (_) {
      return Object.assign({}, DEFAULTS);
    }
  }

  function saveSettings() {
    try {
      localStorage.setItem("WR_SETTINGS", JSON.stringify(settings));
    } catch (_) {
      /* private mode - settings simply do not persist */
    }
  }

  let settings = loadSettings();

  /* --- Interface strings (menu language is separate from word language) ---- */

  const STRINGS = {
    en: {
      loading: "Getting a word ready…",
      go: "Guess a letter!",
      good: ["Great!", "Nice one!", "Keep going!", "You've got this!"],
      bad: ["Not that one!", "Try another!", "Keep trying!"],
      won: "Blast off!",
      lost: "Out of fuel!",
      wordWas: "The word was",
      again: "Play again",
      hint: "Hint",
      turn: "Player %s's turn",
      noSpeech: "Read aloud is not available on this device.",
      stars: "stars",
    },
    ta: {
      loading: "புதிய சொல் தயாராகிறது…",
      go: "ஒரு எழுத்தைத் தேர்ந்தெடு!",
      good: ["அருமை!", "நல்லது!", "தொடர்ந்து முயற்சி செய்!", "சிறப்பு!"],
      bad: ["அது இல்லை!", "வேறு ஒன்றை முயற்சி செய்!", "மீண்டும் முயற்சி செய்!"],
      won: "விண்ணில் பறந்தது!",
      lost: "எரிபொருள் தீர்ந்தது!",
      wordWas: "சரியான சொல்",
      again: "மீண்டும் விளையாடு",
      hint: "குறிப்பு",
      turn: "வீரர் %s இன் முறை",
      noSpeech: "இந்த சாதனத்தில் ஒலி வசதி இல்லை.",
      stars: "நட்சத்திரங்கள்",
    },
  };

  function t(key) {
    const table = STRINGS[settings.ui] || STRINGS.en;
    return table[key] !== undefined ? table[key] : STRINGS.en[key];
  }

  const el = {};
  ["word", "message", "keyboard", "lives", "hint-display", "overlay", "overlay-title",
   "overlay-image", "overlay-word", "overlay-msg", "overlay-again", "overlay-stars",
   "hint-btn", "new-btn", "speak-btn", "stars", "stage", "rocket-wrap", "flame",
   "settings-btn", "sheet-backdrop", "sheet-close", "sheet-done", "reset-stars",
   "turn", "category-label", "keys-nav", "page-prev", "page-next", "page-label"
  ].forEach((id) => { el[id] = document.getElementById(id); });

  let state = null;
  let prev = null;
  let loading = false;
  let keyPage = 0;

  const pick = (a) => a[Math.floor(Math.random() * a.length)];

  /* --- Applying settings to the DOM --------------------------------------- */

  function applySettings() {
    const root = document.documentElement;
    root.dataset.text = settings.text;
    root.dataset.bigkeys = settings.bigkeys;
    root.dataset.motion = settings.motion;
    el["speak-btn"].hidden = settings.speak !== "on" || !("speechSynthesis" in window);
    // Reflect every segmented control's pressed state.
    Object.keys(DEFAULTS).forEach((name) => {
      const box = document.getElementById("opt-" + name);
      if (!box) return;
      box.querySelectorAll("button").forEach((b) => {
        b.setAttribute("aria-pressed", String(b.dataset.v === settings[name]));
      });
    });
  }

  /* --- Sound: short WebAudio blips, no asset files ------------------------- */

  let audioCtx = null;
  function beep(freq, ms, type) {
    if (settings.sound !== "on") return;
    try {
      audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
      const osc = audioCtx.createOscillator();
      const gain = audioCtx.createGain();
      osc.type = type || "sine";
      osc.frequency.value = freq;
      gain.gain.value = 0.06;
      osc.connect(gain).connect(audioCtx.destination);
      osc.start();
      gain.gain.exponentialRampToValueAtTime(0.0001, audioCtx.currentTime + ms / 1000);
      osc.stop(audioCtx.currentTime + ms / 1000);
    } catch (_) { /* audio unavailable - stay silent */ }
  }

  function speak(text) {
    if (settings.speak !== "on" || !("speechSynthesis" in window) || !text) return;
    try {
      window.speechSynthesis.cancel();
      const u = new SpeechSynthesisUtterance(text);
      u.lang = code === "ta" ? "ta-IN" : "en-US";
      u.rate = 0.9;
      window.speechSynthesis.speak(u);
    } catch (_) { /* speech unavailable */ }
  }

  /* --- Rendering ----------------------------------------------------------- */

  function showLoading() {
    loading = true;
    el.word.innerHTML = "";
    for (let i = 0; i < 5; i++) {
      const s = document.createElement("span");
      s.className = "slot skeleton";
      el.word.appendChild(s);
    }
    el.message.textContent = t("loading");
    el.keyboard.innerHTML = "";
    el.lives.innerHTML = "";
    el["hint-display"].textContent = "";
  }

  function renderWord() {
    const before = prev ? prev.masked : null;
    el.word.innerHTML = "";
    el.word.dir = state.direction || "ltr";
    // Scale slots down for long words so they stay on one row.
    const n = state.masked.length;
    el.word.className = "word" + (n > 9 ? " xlong" : n > 6 ? " long" : "");
    state.masked.forEach((tok, i) => {
      const s = document.createElement("span");
      s.className = "slot";
      if (tok === "_") {
        s.textContent = "";
        s.setAttribute("aria-label", "blank");
      } else {
        s.textContent = tok;
        // Newly revealed letters pop; already-known ones stay still.
        if (!before || before[i] === "_") s.classList.add("filled");
        else s.classList.add("filled");
        if (state.is_lost) s.classList.add("reveal");
      }
      el.word.appendChild(s);
    });
  }

  function renderLives() {
    el.lives.innerHTML = "";
    const left = state.remaining;
    for (let i = 0; i < (state.max_wrong || MAX_WRONG); i++) {
      const alive = i < left;
      const cls = "icon life-icon" + (alive ? "" : " gone");
      el.lives.appendChild(iconEl(alive ? ICONS.heart : ICONS.heartEmpty, cls));
    }
    el.lives.setAttribute("aria-label", left + " tries left");
  }

  function renderRocket() {
    // The rocket climbs as letters are found: progress = revealed / total.
    const total = state.masked.length;
    const found = state.masked.filter((m) => m !== "_").length;
    const pct = total ? found / total : 0;
    el["rocket-wrap"].style.bottom = (pct * 78) + "%";
    el.flame.style.display = state.is_over && !state.is_won ? "none" : "";
  }

  function renderKeyboard() {
    el.keyboard.innerHTML = "";
    const all = state.keyboard || [];
    const paged = settings.paged === "on";
    const pages = paged ? Math.ceil(all.length / KEYS_PER_PAGE) : 1;
    if (keyPage >= pages) keyPage = 0;
    const shown = paged
      ? all.slice(keyPage * KEYS_PER_PAGE, (keyPage + 1) * KEYS_PER_PAGE)
      : all;

    shown.forEach((tok) => {
      const b = document.createElement("button");
      b.className = "key";
      b.textContent = tok;
      b.type = "button";
      const guessed = state.guessed.indexOf(tok) !== -1;
      const wrong = state.wrong.indexOf(tok) !== -1;
      if (guessed) {
        b.disabled = true;
        b.classList.add(wrong ? "miss" : "hit");
      }
      if (state.is_over) b.disabled = true;
      b.addEventListener("click", () => guess(tok));
      el.keyboard.appendChild(b);
    });

    // Only show pager controls when paging is on AND there is more than one page.
    el["keys-nav"].hidden = !paged || pages < 2;
    el["page-label"].textContent = (keyPage + 1) + " / " + pages;
    el["page-prev"].disabled = keyPage === 0;
    el["page-next"].disabled = keyPage >= pages - 1;
  }

  function render() {
    loading = false;
    renderWord();
    renderLives();
    renderRocket();
    renderKeyboard();

    el.stars.textContent = state.stars || 0;
    el["category-label"].textContent = state.category
      ? state.category.charAt(0).toUpperCase() + state.category.slice(1)
      : "";

    // Two-player turn indicator
    if (state.two_player && !state.is_over) {
      el.turn.hidden = false;
      el.turn.textContent = t("turn").replace("%s", state.current_player);
    } else {
      el.turn.hidden = true;
    }

    // Always-on hints
    if (settings.hints === "on" && state.hint) {
      el["hint-display"].textContent = state.hint;
    }

    if (state.is_over) showOverlay();
  }

  function showOverlay() {
    const won = state.is_won;
    el["overlay-title"].textContent = won ? t("won") : t("lost");

    el["overlay-image"].innerHTML = "";
    if (won && state.image_url) {
      // A real word-reward picture (Twemoji) - what was actually guessed.
      const img = document.createElement("img");
      img.src = state.image_url;
      img.alt = "";
      img.className = "prize";
      el["overlay-image"].appendChild(img);
    } else {
      el["overlay-image"].appendChild(
        iconEl(won ? ICONS.trophy : ICONS.sad, "icon prize icon-" + (won ? "trophy" : "sad"))
      );
    }

    el["overlay-word"].textContent = state.word || "";
    el["overlay-msg"].textContent = won ? "" : t("wordWas") + " " + (state.word || "");

    el["overlay-stars"].innerHTML = "";
    for (let i = 0; i < (state.earned || 0); i++) {
      const s = iconEl(ICONS.star, "icon icon-star");
      s.style.animationDelay = (i * 0.12) + "s";
      el["overlay-stars"].appendChild(s);
    }

    el.overlay.hidden = false;
    el["overlay-again"].focus();

    if (won) {
      beep(660, 120); setTimeout(() => beep(880, 160), 130);
      if (settings.motion === "on") confetti();
      speak(state.word);
    } else {
      beep(200, 260, "triangle");
    }
  }

  function confetti() {
    const colors = ["#3DDC97", "#FF6B8B", "#FFD34E", "#38BDF8", "#A78BFA"];
    for (let i = 0; i < 40; i++) {
      const p = document.createElement("span");
      p.className = "confetti-piece";
      p.style.left = Math.random() * 100 + "vw";
      p.style.background = colors[i % colors.length];
      p.style.animationDuration = (1.6 + Math.random() * 1.4) + "s";
      p.style.animationDelay = (Math.random() * 0.4) + "s";
      document.body.appendChild(p);
      setTimeout(() => p.remove(), 3400);
    }
  }

  /* --- API ----------------------------------------------------------------- */

  function lengthBounds() {
    if (settings.length === "any") return {};
    const parts = settings.length.split("-");
    return { min_length: parseInt(parts[0], 10), max_length: parseInt(parts[1], 10) };
  }

  async function newGame() {
    showLoading();
    prev = null;
    keyPage = 0;
    el.overlay.hidden = true;
    el["hint-display"].textContent = "";
    const body = Object.assign(
      { code: code, category: settings.category, two_player: settings.two === "on" },
      lengthBounds()
    );
    try {
      const res = await fetch("/api/new", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      state = await res.json();
      if (state.error) { el.message.textContent = state.error; return; }
      render();
      el.message.textContent = t("go");
      if (settings.hints === "on") speak(state.hint);
    } catch (err) {
      el.message.textContent = "Could not start a game: " + err;
    }
  }

  async function guess(token) {
    if (loading || !state || state.is_over) return;
    prev = state;
    try {
      const res = await fetch("/api/guess", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ token: token }),
      });
      const next = await res.json();
      if (next.error) return;
      const wasWrong = next.wrong.length > (prev.wrong ? prev.wrong.length : 0);
      state = next;
      render();
      if (!state.is_over) {
        el.message.textContent = wasWrong ? pick(t("bad")) : pick(t("good"));
      }
      if (wasWrong) {
        beep(180, 140, "square");
        if (settings.motion === "on") {
          el.stage.classList.add("hurt");
          setTimeout(() => el.stage.classList.remove("hurt"), 420);
        }
      } else {
        beep(520, 90);
      }
    } catch (_) { /* network hiccup - the board stays as it was */ }
  }

  /* --- Options UI ---------------------------------------------------------- */

  async function buildCategoryOptions() {
    const box = document.getElementById("opt-category");
    box.innerHTML = "";
    const mk = (value, label) => {
      const b = document.createElement("button");
      b.dataset.v = value;
      b.textContent = label;
      b.setAttribute("aria-pressed", String(settings.category === value));
      b.addEventListener("click", () => setOption("category", value, true));
      box.appendChild(b);
    };
    mk("all", "All words");
    try {
      const res = await fetch("/api/categories/" + code);
      const data = await res.json();
      (data.categories || []).forEach((c) => {
        mk(c.name, c.name.charAt(0).toUpperCase() + c.name.slice(1) + " (" + c.count + ")");
      });
    } catch (_) { /* leave just "All words" */ }
  }

  function setOption(name, value, restart) {
    settings[name] = value;
    saveSettings();
    applySettings();
    if (name === "hints") {
      el["hint-display"].textContent =
        value === "on" && state && state.hint ? state.hint : "";
    }
    if (name === "paged") { keyPage = 0; if (state) renderKeyboard(); }
    if (name === "ui" && state) render();
    if (restart) newGame();
  }

  function wireOptionGroup(name) {
    const box = document.getElementById("opt-" + name);
    if (!box) return;
    box.addEventListener("click", (e) => {
      const b = e.target.closest("button");
      if (!b || !b.dataset.v) return;
      // Category and length change the word pool, so they start a fresh round.
      setOption(name, b.dataset.v, name === "length" || name === "two");
    });
  }

  /* --- Wiring -------------------------------------------------------------- */

  ["length", "text", "bigkeys", "paged", "motion", "sound", "speak", "hints", "two", "ui"]
    .forEach(wireOptionGroup);

  el["new-btn"].addEventListener("click", newGame);
  el["overlay-again"].addEventListener("click", newGame);

  el["hint-btn"].addEventListener("click", () => {
    if (!state) return;
    el["hint-display"].textContent = state.hint || "";
    speak(state.hint);
  });

  el["speak-btn"].addEventListener("click", () => {
    if (!state) return;
    speak(state.hint || "");
  });

  el["settings-btn"].addEventListener("click", () => {
    el["sheet-backdrop"].hidden = false;
    el["sheet-close"].focus();
  });
  const closeSheet = () => { el["sheet-backdrop"].hidden = true; el["settings-btn"].focus(); };
  el["sheet-close"].addEventListener("click", closeSheet);
  el["sheet-done"].addEventListener("click", closeSheet);
  el["sheet-backdrop"].addEventListener("click", (e) => {
    if (e.target === el["sheet-backdrop"]) closeSheet();
  });

  el["reset-stars"].addEventListener("click", async () => {
    try {
      await fetch("/api/stars", { method: "POST" });
      el.stars.textContent = "0";
      if (state) state.stars = 0;
    } catch (_) { /* ignore */ }
  });

  el["page-prev"].addEventListener("click", () => { keyPage = Math.max(0, keyPage - 1); renderKeyboard(); });
  el["page-next"].addEventListener("click", () => { keyPage += 1; renderKeyboard(); });

  // Physical keyboard support (English packs).
  document.addEventListener("keydown", (e) => {
    if (!el["sheet-backdrop"].hidden) {
      if (e.key === "Escape") closeSheet();
      return;
    }
    if (!el.overlay.hidden) {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); newGame(); }
      return;
    }
    if (e.metaKey || e.ctrlKey || e.altKey) return;
    const ch = e.key.toUpperCase();
    if (ch.length === 1 && state && state.keyboard && state.keyboard.indexOf(ch) !== -1) {
      guess(ch);
    }
  });

  // Twinkling stars
  const orbs = document.querySelector(".orbs");
  for (let i = 0; i < 26; i++) {
    const s = document.createElement("span");
    s.className = "twinkle";
    s.style.left = Math.random() * 100 + "%";
    s.style.top = Math.random() * 100 + "%";
    s.style.animationDelay = (Math.random() * 3).toFixed(2) + "s";
    orbs.appendChild(s);
  }

  applySettings();
  buildCategoryOptions();
  newGame();
})();
